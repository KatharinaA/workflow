/** Returns benefits for a given business name, sorted best deal first */
export const getBenefitsForBusiness = (businessName: string): Benefit[] =>
  ALL_BENEFITS
    .filter((b) => b.businessName === businessName)
    .sort((a, b) => b.discountValue - a.discountValue);
